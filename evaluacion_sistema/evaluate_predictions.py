"""
Evaluate ALREADY-GENERATED predictions with the FULL system pipeline.

This script runs the exact same pipeline as evaluate_system.py -- verification
with Batfish plus the refinement (repair) loop -- with ONE difference: the
initial configuration is NOT generated by the model. It is read from a CSV of
predictions produced beforehand.

Pipeline per row (identical to evaluate_system.py from step 4 onwards):
  1. The prediction from the CSV is injected as the model's first output.
  2. ExecutionController._verify_configuration -> Batfish (first pass).
  3. If it fails, ExecutionController._refinement_loop asks the FLM to repair
     the flagged lines, re-verifying after each attempt (up to 3 iterations).
  4. Metrics are reported exactly like the full system: first-pass success,
     final success, refinement success, max-iterations-reached, ROUGE.

Because the refinement loop prompts the model with the ORIGINAL requirement,
the input CSV must contain a 'requirement' column (see below).

Input CSV columns:
  - prediction (required) : final_prediction | prediction | predictions | generated_config
  - requirement (required): requirement | request | intent
  - reference (optional)  : ground_truth | configuration | confguration | reference   (for ROUGE)

Folder layout (default, no arguments needed) -- relative to this script:
  evaluacion_sistema/prueba/predicciones/   <- drop your prediction CSVs here
  evaluacion_sistema/prueba/resultados/     <- per-file results are written here

Usage (runnable from anywhere):
  # Evaluate EVERY csv in prueba/predicciones/, writing results to prueba/resultados/
  python evaluacion_sistema/evaluate_predictions.py

  # Or point it at a single file explicitly
  python evaluacion_sistema/evaluate_predictions.py --input path/to/predictions.csv
  python evaluacion_sistema/evaluate_predictions.py --input preds.csv --limit 20 --output results.csv

  # Verify only, skipping the repair loop (the old behaviour of this script)
  python evaluacion_sistema/evaluate_predictions.py --no-refine
"""

import argparse
import csv
import statistics
import sys
import time
import uuid
from pathlib import Path

# This script lives in evaluacion_sistema/; the actual code lives under Orchestrator/.
EVAL_DIR = Path(__file__).resolve().parent
REPO_ROOT = EVAL_DIR.parent
PROJECT_ROOT = REPO_ROOT / "Orchestrator"
for _p in (PROJECT_ROOT, EVAL_DIR):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

from core.execution_controller import ExecutionController
from core.prompt_manager import PromptManager
from core.requirement_loader import RequirementLoader
from mcp_client import MCPClientManager, SERVERS
from models.execution_context import ExecutionContext
from models.state import ExecutionState

# Reuse the full-system evaluator's helpers so the metrics are computed identically.
from evaluate_system import (
    DEFAULT_RAG_FILTERS,
    EvaluationResultLogger,
    compute_rouge,
    verification_statuses,
)


PRUEBA_DIR = EVAL_DIR / "prueba"
INPUT_DIR = PRUEBA_DIR / "predicciones"
OUTPUT_DIR = PRUEBA_DIR / "resultados"

PREDICTION_COLUMNS = ["final_prediction", "prediction", "predictions", "generated_config"]
REQUIREMENT_COLUMNS = ["requirement", "request", "intent"]
REFERENCE_COLUMNS = ["ground_truth", "configuration", "confguration", "reference"]

EMPTY_PREDICTIONS = ("", "ERROR", "NO_CODE")


def _pick_column(header, candidates):
    return next((c for c in candidates if c in header), None)


def read_predictions(path, require_requirement=True):
    with open(path, newline="", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))

    if not rows:
        raise ValueError("Prediction CSV is empty.")

    header = rows[0].keys()
    prediction_col = _pick_column(header, PREDICTION_COLUMNS)
    if not prediction_col:
        raise ValueError(
            "Could not find a prediction column. Expected one of: "
            + ", ".join(PREDICTION_COLUMNS)
        )

    requirement_col = _pick_column(header, REQUIREMENT_COLUMNS)
    if require_requirement and not requirement_col:
        raise ValueError(
            "Could not find a requirement column, which the refinement loop needs to "
            "prompt the model. Expected one of: " + ", ".join(REQUIREMENT_COLUMNS)
            + ". Run with --no-refine to verify without repairing."
        )

    reference_col = _pick_column(header, REFERENCE_COLUMNS)
    return rows, prediction_col, requirement_col, reference_col


def build_requirement(requirement_text, row_id=None):
    """Build the same requirement dict evaluate_system.py feeds the controller."""
    if isinstance(requirement_text, str) and requirement_text.strip():
        requirement = RequirementLoader().load(requirement_text)
    else:
        # Only reachable with --no-refine, where no prompt is ever built from it.
        requirement = {"request_id": str(uuid.uuid4()), "intent": ""}

    requirement["source"] = "prediction_csv"
    requirement["dataset_row_id"] = row_id or str(uuid.uuid4())
    requirement["rag_filters"] = DEFAULT_RAG_FILTERS
    return requirement


def run_prediction(controller, prediction_text, requirement_text, refine=True):
    """Verify one already-generated prediction, then repair it like the full system.

    This mirrors ExecutionController.run() minus the RAG + generation steps: the
    CSV prediction takes the place of the model's first configuration output.
    """
    context = ExecutionContext(build_requirement(requirement_text))

    # Inject the prediction where the generation step would have left it.
    context.final_result = prediction_text

    verification_success = controller._verify_configuration(context)

    if not verification_success and refine:
        controller._refinement_loop(context)

    if context.state != ExecutionState.SUCCESS:
        if context.state == ExecutionState.RUNNING:
            context.mark_failed("Execution finished without a successful verification.")

    return context


def _failure_reason(context):
    """Extract a short, human-readable reason from the last VERIFICATION_CALL."""
    data = None
    for iteration in reversed(context.iterations):
        if iteration.get("prompt") == "VERIFICATION_CALL":
            data = iteration.get("response", {}).get("data")
            break

    if isinstance(data, dict):
        errors = data.get("errors")
        if isinstance(errors, list) and errors:
            first = errors[0]
            if isinstance(first, dict):
                status = first.get("Status", "FAILED")
                line = first.get("Invalid line") or first.get("File") or ""
                reason = first.get("Reason", "")
                detail = " | ".join(p for p in (status, str(line).strip(), reason) if p)
                return detail or "verification failed"
        failed = data.get("failed_files") or data.get("results")
        if failed:
            return f"Batfish parse issues: {failed}"
    if isinstance(data, str) and data:
        return data
    return "Batfish verification failed"


def evaluate_file(controller, input_path, output_path=None, limit=None, refine=True):
    """Evaluate a single predictions CSV. Returns a stats dict."""
    rows, prediction_col, requirement_col, reference_col = read_predictions(
        input_path, require_requirement=refine
    )
    if limit:
        rows = rows[:limit]

    total = len(rows)
    predictions = []
    references = []
    latencies = []
    csv_rows = []
    states = []
    first_pass_successes = 0
    final_batfish_successes = 0
    refinement_successes = 0
    max_iterations_reached = 0
    empty_count = 0

    print(f"\n{'#' * 60}")
    print(f"# File: {Path(input_path).name}  ({total} predictions)")
    print(f"{'#' * 60}")

    for index, row in enumerate(rows, start=1):
        prediction = (row.get(prediction_col) or "").strip()
        requirement_text = (row.get(requirement_col) or "") if requirement_col else ""
        reference = (row.get(reference_col) or "") if reference_col else ""

        label = str(requirement_text or f"row_{index}").replace("\n", " ")
        if len(label) > 70:
            label = label[:67] + "..."

        # An empty / ERROR / NO_CODE prediction has nothing to verify or repair.
        if prediction.upper() in EMPTY_PREDICTIONS:
            empty_count += 1
            print(f"[{index}/{total}] {label}  ->  FAIL  (empty / ERROR / NO_CODE prediction)")
            predictions.append(prediction)
            references.append(reference)
            latencies.append(0.0)
            states.append(ExecutionState.FAILED.value)
            csv_rows.append({
                "requirement": requirement_text,
                "ground_truth": reference,
                "original_prediction": prediction,
                "final_prediction": prediction,
            })
            continue

        start = time.time()
        context = run_prediction(controller, prediction, requirement_text, refine=refine)
        elapsed = time.time() - start

        final_prediction = getattr(context, "generated_config", "") or ""
        statuses = verification_statuses(context)
        first_pass_ok = bool(statuses and statuses[0] == "success")
        final_ok = context.state == ExecutionState.SUCCESS
        # Each repair attempt triggers exactly one extra verification call.
        refinement_attempts = max(0, len(statuses) - 1)
        refined_to_success = final_ok and not first_pass_ok and refinement_attempts > 0

        if first_pass_ok:
            first_pass_successes += 1
            print(f"[{index}/{total}] {label}  ->  PASS (first pass)")
        elif final_ok:
            print(f"[{index}/{total}] {label}  ->  PASS (repaired in {refinement_attempts} iter)")
        else:
            print(f"[{index}/{total}] {label}  ->  FAIL  ({_failure_reason(context)})")

        if final_ok:
            final_batfish_successes += 1
        if refined_to_success:
            refinement_successes += 1
        if context.state == ExecutionState.MAX_ITERATIONS_REACHED:
            max_iterations_reached += 1

        predictions.append(final_prediction)
        references.append(reference)
        latencies.append(elapsed)
        states.append(context.state.value)
        csv_rows.append({
            "requirement": requirement_text,
            "ground_truth": reference,
            "original_prediction": prediction,
            "final_prediction": final_prediction,
        })

    def rate(value):
        return round(value / total, 4) if total else 0.0

    failed_count = sum(1 for state in states if state == ExecutionState.FAILED.value)
    avg_time = statistics.mean(latencies) if latencies else 0.0

    print("\n" + "=" * 60)
    print(f"SUMMARY - {Path(input_path).name}")
    print("=" * 60)
    print(f"Total predictions: {total}")
    print(f"Total time: {round(sum(latencies), 2)}s")
    print(f"Average time/prediction: {round(avg_time, 3)}s")
    print(f"Empty/ERROR/NO_CODE: {empty_count}")
    print(f"First-pass Batfish success: {first_pass_successes}/{total} ({rate(first_pass_successes)})")
    print(f"Final Batfish success: {final_batfish_successes}/{total} ({rate(final_batfish_successes)})")
    print(f"Refinement success: {refinement_successes}/{total} ({rate(refinement_successes)})")
    print(f"Max iterations reached: {max_iterations_reached}")
    print(f"Failed: {failed_count}")
    if reference_col:
        print("Final ROUGE:", compute_rouge(predictions, references))

    if output_path:
        Path(output_path).parent.mkdir(parents=True, exist_ok=True)
        fields = ["requirement", "ground_truth", "original_prediction", "final_prediction"]
        with open(output_path, "w", newline="", encoding="utf-8-sig") as f:
            writer = csv.DictWriter(f, fieldnames=fields)
            writer.writeheader()
            writer.writerows(csv_rows)
        print(f"\nResults written to: {output_path}")

    return {
        "total": total,
        "first_pass": first_pass_successes,
        "final": final_batfish_successes,
        "refined": refinement_successes,
    }


def build_controller(refine=True):
    """Create the ExecutionController and start the MCP servers it needs."""
    templates_path = PROJECT_ROOT / "templates"
    prompt_manager = PromptManager(templates_path=str(templates_path))
    mcp_client_manager = MCPClientManager(SERVERS)

    controller = ExecutionController(
        prompt_manager=prompt_manager,
        mcp_client=mcp_client_manager,
        result_logger=EvaluationResultLogger(),
    )

    batfish_server = mcp_client_manager.server("batfish")
    batfish_server.start()
    batfish_server.initialize()

    # The refinement loop prompts the model to repair the flagged lines.
    if refine:
        flm_server = mcp_client_manager.server("flm")
        flm_server.start()
        flm_server.initialize()

    return controller, mcp_client_manager


def run(input_path=None, output_path=None, limit=None, refine=True):
    """Evaluate either a single --input file, or every CSV in prueba/predicciones/."""
    if input_path:
        jobs = [(Path(input_path),
                 Path(output_path) if output_path
                 else OUTPUT_DIR / f"{Path(input_path).stem}_resultados.csv")]
    else:
        OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
        csv_files = sorted(p for p in INPUT_DIR.glob("*.csv"))
        if not csv_files:
            print(f"No prediction CSVs found in: {INPUT_DIR}")
            print("Drop your prediction files there (or pass --input path.csv) and run again.")
            return
        jobs = [(p, OUTPUT_DIR / f"{p.stem}_resultados.csv") for p in csv_files]

    controller, mcp_client_manager = build_controller(refine=refine)
    grand = {"total": 0, "first_pass": 0, "final": 0, "refined": 0}
    try:
        for in_path, out_path in jobs:
            stats = evaluate_file(controller, in_path, out_path, limit, refine=refine)
            for key in grand:
                grand[key] += stats[key]
    finally:
        mcp_client_manager.close_all()

    if len(jobs) > 1:
        total = grand["total"]

        def rate(value):
            return round(value / total, 4) if total else 0.0

        print("\n" + "*" * 60)
        print(f"OVERALL across {len(jobs)} files ({total} predictions)")
        print(f"  First-pass success: {grand['first_pass']}/{total} ({rate(grand['first_pass'])})")
        print(f"  Final success     : {grand['final']}/{total} ({rate(grand['final'])})")
        print(f"  Refinement success: {grand['refined']}/{total} ({rate(grand['refined'])})")
        print("*" * 60)


def main():
    parser = argparse.ArgumentParser(
        description="Evaluate already-generated predictions with the full system pipeline "
                    "(Batfish verification + refinement loop, no generation)."
    )
    parser.add_argument(
        "--input",
        default=None,
        help="Path to a single predictions CSV. If omitted, reads every CSV in prueba/predicciones/.",
    )
    parser.add_argument("--output", default=None, help="Optional path for the results CSV (single-file mode).")
    parser.add_argument("--limit", type=int, default=None, help="Optional limit for quick runs.")
    parser.add_argument(
        "--no-refine",
        action="store_true",
        help="Skip the repair loop: verify each prediction once and report PASS/FAIL only.",
    )
    args = parser.parse_args()

    run(
        input_path=Path(args.input) if args.input else None,
        output_path=Path(args.output) if args.output else None,
        limit=args.limit,
        refine=not args.no_refine,
    )


if __name__ == "__main__":
    main()
